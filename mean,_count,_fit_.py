# --- Cell 1: Imports ---
import numpy as np
import matplotlib.pyplot as plt
from tqdm import tqdm


# --- Cell 2: SquareWell class ---
class SquareWell:
    def __init__(self, size: float, mode: str = "reflect") -> None:
        self.L = size
        self.mode = mode

    def random_position(self):
        return tuple(np.random.uniform(0, self.L, size=2))

    def apply_boundary(self, x, y):
        if self.mode == "reflect":
            return np.clip(x, 0, self.L), np.clip(y, 0, self.L)
        else:  # wrap
            return x % self.L, y % self.L


# --- Cell 3: Cell dataclasses ---
from dataclasses import dataclass

@dataclass
class ECell:
    x: float
    y: float

@dataclass
class TCell:
    x: float
    y: float

@dataclass
class CCell:
    x: float
    y: float


# --- Cell 4: ABM Simulation Class ---
class WellSimulation:
    def __init__(self, E_0, T_0, r, m, N, L, k_on, k_off, k_kill, g_E, g_T, early_stop, log_all=False, seed=None):
        if seed is not None:
            np.random.seed(seed)

        self.E_0 = E_0
        self.T_0 = T_0
        self.r = r
        self.m = m
        self.N = N
        self.L = L
        self.k_on = k_on
        self.k_off = k_off
        self.k_kill = k_kill
        self.g_E = g_E
        self.g_T = g_T
        self.early_stop = early_stop
        self.log_all = log_all

        self.history = {"E": [], "T": [], "C": []}
        self.well = SquareWell(L)

        self.e_cells = [ECell(*self.well.random_position()) for _ in range(E_0)]
        self.t_cells = [TCell(*self.well.random_position()) for _ in range(T_0)]
        self.existing_c_cells = []
        self.new_c_cells = []
        self.simulated = False
        self._log()

    def _combine_behavior(self):
        from scipy.spatial import cKDTree
        e_coords = np.array([[e.x, e.y] for e in self.e_cells])
        t_coords = np.array([[t.x, t.y] for t in self.t_cells])
        if len(e_coords) == 0 or len(t_coords) == 0:
            return
        tree = cKDTree(t_coords)
        neighbor_indices = tree.query_ball_point(e_coords, r=2 * self.r)
        taken_t = set()
        new_c = []
        remaining_e = []

        for i, t_neighbors in enumerate(neighbor_indices):
            np.random.shuffle(t_neighbors)
            for j in t_neighbors:
                if j in taken_t:
                    continue
                if np.random.rand() < self.k_on:
                    ex, ey = e_coords[i]
                    tx, ty = t_coords[j]
                    new_c.append(CCell((ex + tx) / 2, (ey + ty) / 2))
                    taken_t.add(j)
                    break
            else:
                remaining_e.append(ECell(*e_coords[i]))

        self.t_cells = [t for j, t in enumerate(self.t_cells) if j not in taken_t]
        self.new_c_cells = new_c
        self.e_cells = remaining_e

    def _c_cell_behavior(self):
        remaining_c = []
        for c in self.existing_c_cells:
            rnd = np.random.rand()
            if rnd < self.k_off:
                self.e_cells.append(ECell(c.x, c.y))
                self.t_cells.append(TCell(c.x, c.y))
            elif rnd < self.k_off + self.k_kill:
                self.e_cells.append(ECell(c.x, c.y))
            else:
                remaining_c.append(c)
        self.existing_c_cells = remaining_c

    def _cell_move(self):
        moved = []
        for e in self.e_cells:
            dx, dy = np.random.normal(0, self.m, size=2)
            x, y = self.well.apply_boundary(e.x + dx, e.y + dy)
            moved.append(ECell(x, y))
        self.e_cells = moved

    def _cell_grow(self):
        new_e = []
        for e in self.e_cells:
            if np.random.rand() < self.g_E:
                dx, dy = np.random.uniform(-self.r, self.r, 2)
                x, y = self.well.apply_boundary(e.x + dx, e.y + dy)
                new_e.append(ECell(x, y))
        self.e_cells.extend(new_e)

        new_t = []
        for t in self.t_cells:
            if np.random.rand() < self.g_T:
                dx, dy = np.random.uniform(-self.r, self.r, 2)
                x, y = self.well.apply_boundary(t.x + dx, t.y + dy)
                new_t.append(TCell(x, y))
        self.t_cells.extend(new_t)

    def _log(self):
        self.history["E"].append(len(self.e_cells))
        self.history["T"].append(len(self.t_cells))
        self.history["C"].append(len(self.existing_c_cells) + len(self.new_c_cells))
        self.existing_c_cells += self.new_c_cells
        self.new_c_cells = []

    def _step(self):
        self._cell_move()
        self._combine_behavior()
        self._c_cell_behavior()
        self._cell_grow()
        self._log()

    def run(self):
        unchanged = 0
        prev_T = self.history["T"][-1]
        for _ in range(self.N):
            self._step()
            curr_T = self.history["T"][-1]
            if prev_T * (1 - self.early_stop[1]) <= curr_T <= prev_T * (1 + self.early_stop[1]):
                unchanged += 1
            else:
                unchanged = 0
            prev_T = curr_T
            if curr_T == 0 and self.history["C"][-1] == 0:
                break
            if self.history["E"][-1] == 0 and self.history["C"][-1] == 0:
                break
            if unchanged >= self.early_stop[0]:
                break
        self.simulated = True


