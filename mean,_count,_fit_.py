def extract_initial_conditions(filename):
    match = re.search(r"E-(\d+)_T-(\d+)", filename)
    if match:
        E0 = int(match.group(1))
        T0 = int(match.group(2))
        return E0, T0
    else:
        raise ValueError(f"Filename {filename} does not match expected pattern.")

# --- 1-ODE Model Function (Analytical Solution) ---
def model_T(t, T0, E0, k_on, k_off, k_kill, g):
    rate = g - (k_on * k_kill / (k_off + k_kill)) * E0
    return T0 * np.exp(rate * t)

# --- Objective Function: Avg Normalized RMSE ---
def objective(params, datasets):
    k_on, k_off, k_kill, g = params
    total_error = 0
    for data in datasets:
        t = data['time']
        T_obs = data['T']
        T0 = T_obs[0]
        E0 = data['E0']
        T_pred = model_T(t, T0, E0, k_on, k_off, k_kill, g)
        rmse = np.sqrt(np.mean((T_obs - T_pred) ** 2))
        norm = np.mean(T_obs)
        total_error += rmse / norm
    return total_error / len(datasets)

